"""Generate the five reference skins from the original screenshots (Pillow required)."""

import argparse
import base64
import json
from pathlib import Path
from statistics import median

from PIL import Image


PARTS = ('head', 'torso', 'arm', 'leg')
FACES = ('front', 'right', 'back', 'left', 'top', 'bottom')
# Face panel edges, in original screenshot pixels. The 64x64 overview
# sometimes differs from the labeled face panels; use the latter throughout.
SHEETS = {
    'cipher': ('27.51', (2302, 1514), [(210, 336), (465, 592), (728, 853), (986, 1115)],
               [(1446, 1568), (1588, 1702), (1720, 1838), (1858, 1974), (1996, 2113), (2134, 2251)]),
    'frost': ('30.22', (2286, 1526), [(208, 334), (464, 590), (726, 851), (984, 1112)],
              [(1451, 1572), (1592, 1706), (1725, 1842), (1863, 1978), (2000, 2117), (2139, 2255)]),
    'atlas': ('34.01', (2276, 1522), [(204, 330), (460, 586), (722, 846), (981, 1109)],
              [(1439, 1560), (1581, 1694), (1713, 1830), (1851, 1966), (1990, 2105), (2128, 2243)]),
    'ace': ('35.21', (2272, 1518), [(202, 328), (458, 584), (720, 845), (978, 1107)],
            [(1437, 1558), (1578, 1692), (1711, 1828), (1849, 1964), (1987, 2103), (2126, 2241)]),
    'nomad': ('38.48', (2290, 1518), [(196, 322), (452, 578), (714, 838), (972, 1101)],
              [(1443, 1564), (1584, 1698), (1717, 1834), (1855, 1970), (1993, 2109), (2132, 2247)]),
}


def sample_tile(image, x_edges, y_edges):
    # Inset past the panel border, and take a small median sample at each
    # texel center so the printed grid doesn't become part of the texture.
    x0, x1 = x_edges[0] + 2, x_edges[1] - 2
    y0, y1 = y_edges[0] + 2, y_edges[1] - 2
    pixels = image.load()
    rgb = bytearray()
    for row in range(16):
        y = round(y0 + (row + .5) * (y1 - y0) / 16)
        for col in range(16):
            x = round(x0 + (col + .5) * (x1 - x0) / 16)
            neighborhood = [pixels[x + dx, y + dy] for dy in (-1, 0, 1) for dx in (-1, 0, 1)]
            rgb.extend(median(channel) for channel in zip(*neighborhood))
    return base64.b64encode(rgb).decode('ascii')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('screenshots', type=Path, help='Directory containing the original five screenshots')
    args = parser.parse_args()
    skins = {}
    for name, (timestamp, size, rows, columns) in SHEETS.items():
        paths = list(args.screenshots.glob(f'Screenshot 2026-11-12 at 3.{timestamp}*PM.png'))
        if len(paths) != 1:
            parser.error(f'Expected one original sheet for {name}: found {len(paths)}')
        with Image.open(paths[0]) as source:
            if source.size != size:
                parser.error(f'Wrong size for {name}: expected {size}, got {source.size}')
            image = source.convert('RGB')
        skins[name] = {
            part: {face: sample_tile(image, x, y) for face, x in zip(FACES, columns)}
            for part, y in zip(PARTS, rows)
        }
    output = Path(__file__).resolve().parents[1] / 'public' / 'arena-character-textures.js'
    output.write_text('// Generated by tools/sample-character-sheets.py from the supplied face panels.\n'
                      '// Each tile is 16 x 16 RGB pixels in row-major order.\n'
                      'window.PVP_ARENA_CHARACTER_FACES = ' + json.dumps(skins, indent=2) + ';\n', encoding='ascii')


if __name__ == '__main__':
    main()
