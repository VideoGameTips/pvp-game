const assert=require('node:assert/strict');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async()=>{
  const browser=await chromium.launch({headless:true});
  try{
    const page=await browser.newPage({viewport:{width:1280,height:850}}),errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.goto(process.env.PVP_TEST_URL || 'http://localhost:3001/');
    await page.waitForFunction(()=>window.PVP_BATTLE_SIM && myId);
    await page.evaluate(()=>{requestAnimationFrame=()=>0;});await page.waitForTimeout(100);
    const result=await page.evaluate(async()=>{
      await PVP_RAGDOLL.ready;
      const sim=PVP_BATTLE_SIM;
      document.getElementById('overlay').style.display='none';
      document.body.classList.remove('login-open');
      selectMode('battle_simulator');
      const select=document.getElementById('bs-map');select.value='duel_grid';select.onchange();
      const options=[...document.querySelectorAll('#bs-weapon option')];
      if(!options.some(o=>o.value==='combat_axe')||!options.some(o=>o.value==='omega_pistol'))throw Error('Missing melee/admin weapons');
      if(options.some(o=>WEAPONS.find(w=>w.id===o.value)?.archived))throw Error('Archived weapons offered');
      sim.state.weapon='combat_axe';sim.state.utility='frag';sim.state.hp=3000;
      const found=[];
      for(let z=-20;z<20;z+=3)for(let x=-20;x<20;x+=3){
        if(found.length===2)break;
        if(found.length&&(Math.hypot(x-found[0].x,z-found[0].z)>4||!hasLineOfSight(x,z,found[0].x,found[0].z)))continue;
        sim.state.team=found.length?'enemy':'ally';
        if(sim.place(new THREE.Vector3(x,0,z)))found.push({x,z});
      }
      if(found.length!==2)throw Error('No placement');
      sim.start();
      // Freeze navigation/render cost; exercise the simulator combat and ragdoll frame itself.
      const nativeAI=updateBotAI,nativeRender=renderer.render;
      updateBotAI=()=>{};renderer.render=()=>{};
      const attacker=gameBots[0],victim=gameBots[1];
      if(attacker.meleeId!=='combat_axe'||attacker.utilityId!=='frag')throw Error('Loadout not applied');
      attacker._simAbilityAt=0;victim._simAbilityAt=Infinity;victim._simAttackAt=Infinity;victim._simUtilityAt=Infinity;
      sim.frame(.05);
      if(!attacker._simAction?.spin)throw Error('No battleaxe whirlwind');
      const before=victim.hp;
      for(let i=0;i<12;i++)sim.frame(.05);
      if(victim.hp>=before)throw Error('Melee did not damage target');
      const usedBefore=attacker._simUtilityUses;
      attacker._simUtilityAt=0;sim.frame(.05);
      if(attacker._simUtilityUses>=usedBefore)throw Error('Utility not used');
      attacker._simUtilityAt=Infinity;
      sim.state.phase='paused';const hp=victim.hp,x=attacker.x;
      sim.frame(.5);if(victim.hp!==hp||attacker.x!==x)throw Error('Pause advanced combat');
      sim.state.phase='running';
      victim.utilityId='medkit';victim._simUtilityAt=0;victim.hp=100;
      attacker._simAction=null;attacker._simAbilityAt=Infinity;attacker._simAttackAt=Infinity;
      victim._simAttackAt=Infinity;sim.frame(.05);
      if(!victim._simHeal)throw Error('No medkit heal channel');
      sim.damage(victim,attacker,1,'ak20');
      if(victim._simHeal)throw Error('Damage did not interrupt healing');
      sim.damage(victim,attacker,10000,'frag');sim.frame(.05);
      const corpse=remoteMeshes[victim.id]._ragdoll;
      if(!corpse?.dead||!corpse.explosive)throw Error('No explosive death ragdoll');
      if(sim.state.phase!=='finished')throw Error('No winner');
      sim.edit();
      if(gameBots.some(b=>b.dead)||gameBots.some(b=>remoteMeshes[b.id]._ragdoll))throw Error('Reset retained corpses');
      sim.state.units[0].weapon='omega_pistol';sim.start();
      if(gameBots[0].weaponId!=='omega_pistol')throw Error('Admin loadout did not apply');
      updateBotAI=nativeAI;
      gameBots[0].lastShot=0;gameBots[0].reactionMs=0;
      for(let i=0;i<10&&!gameBots[1].dead;i++)sim.frame(.05);
      if(!gameBots[1].dead)throw Error('Admin weapon damage failed');
      sim.edit();sim.state.units[0].weapon='ak20';sim.start();updateBotAI=()=>{};
      gameBots[0]._simAbilityAt=0;gameBots[0]._simUtilityAt=Infinity;
      gameBots[1]._simAbilityAt=Infinity;gameBots[1]._simAttackAt=Infinity;gameBots[1]._simUtilityAt=Infinity;
      sim.frame(.05);
      if(Math.abs(sim.shotDamage(gameBots[0],WEAPONS.find(w=>w.id==='ak20'),10)-14)>.001)throw Error('Gun damage buff failed');
      sim.edit();sim.state.units[0].weapon='storm_bloom';sim.start();
      gameBots[0]._simAbilityAt=0;gameBots[0]._simUtilityAt=Infinity;
      gameBots[1]._simAbilityAt=Infinity;gameBots[1]._simAttackAt=Infinity;gameBots[1]._simUtilityAt=Infinity;
      const orbTarget=gameBots[1],orbHp=orbTarget.hp;
      for(let i=0;i<45;i++)sim.frame(.05);
      const orbDamage=orbHp-orbTarget.hp;
      if(!(orbDamage>0&&orbDamage<=110))throw Error('Lightning damage repeated: '+orbDamage);
      if(orbTarget._rootUntil>Date.now()&&!sim.canFire(orbTarget))throw Error('Root blocked shooting');
      updateBotAI=nativeAI;renderer.render=nativeRender;
      sim.edit();
      return {melee:true,whirlwind:true,utility:true,healInterruption:true,explosiveRagdoll:true,admin:true,gunBuff:true,lightning:true,pause:true,reset:true};
    });
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.click('#bs-exit');
    assert.equal(await page.evaluate(()=>!PVP_BATTLE_SIM.active && gameBots.length===0),true);
    assert.deepEqual(errors,[]);
    console.log('PASS',result);
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
