#!/usr/bin/env node
// Writes public/sound-data.js: every recording in SAMPLE_FILES (public/game.js), base64, as `window.SOUND_DATA = { "sounds/x.mp3": "..." }`.
//
// Why a script and not fetch('sounds/x.mp3'): a page opened as a file (double-clicking index.html) is not allowed to fetch() anything, so the
// recordings never loaded and the made-up shots played instead. A <script src> loads from a file, from a server and from itch alike.
// (It is its own file, not a block inside index.html, because index.html is the one file Cloudflare never caches: ~400 KB of audio in it would be
// downloaded again on every visit. sound-data.js is in VERSIONED in server.js, so a changed sound gets a new URL like game.js does.)
//
//   node tools/embed-sounds.js           rewrite public/sound-data.js from public/sounds/*.mp3 (run it after changing a sound)
//   node tools/embed-sounds.js --check   exit 1 if public/sound-data.js is not exactly what the files and SAMPLE_FILES say
//                                        (verify-boot --sample and tools/build-itch.sh run this)
const fs = require('fs'), path = require('path');
const pub = path.join(__dirname, '..', 'public'), out = path.join(pub, 'sound-data.js');

const game = fs.readFileSync(path.join(pub, 'game.js'), 'utf8');
const block = (game.match(/const SAMPLE_FILES = \{([\s\S]*?)\n\};/) || [])[1];
if (!block) { console.error('embed-sounds: no SAMPLE_FILES table in public/game.js'); process.exit(2); }
const urls = [...block.matchAll(/'(sounds\/[^']+\.mp3)'/g)].map(m => m[1]);
if (!urls.length) { console.error('embed-sounds: SAMPLE_FILES lists no files'); process.exit(2); }

const data = {};
for (const u of urls) {
  const f = path.join(pub, u);
  if (!fs.existsSync(f)) { console.error('embed-sounds: public/' + u + ' is listed in SAMPLE_FILES but is not there'); process.exit(2); }
  data[u] = fs.readFileSync(f).toString('base64');
}

const text = '// GENERATED by tools/embed-sounds.js from public/sounds/*.mp3 (the files named in SAMPLE_FILES in game.js). Do not edit: run `node tools/embed-sounds.js` after changing a sound.\n'
  + '// The recordings travel inside this script so they play wherever the game opens: a page opened as a file may not fetch() anything, and a script can always be loaded.\n'
  + 'window.SOUND_DATA = {\n' + urls.map(u => '  ' + JSON.stringify(u) + ': ' + JSON.stringify(data[u])).join(',\n') + '\n};\n';

if (process.argv.includes('--check')) {
  const have = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (have !== text) {
    const sound = {}; try { new Function('window', have)(sound); } catch (e) {}
    const got = sound.SOUND_DATA || {}, why = [];
    for (const u of urls) if (got[u] !== data[u]) why.push(u + (got[u] ? ' differs from its file' : ' is missing'));
    for (const u of Object.keys(got)) if (!urls.includes(u)) why.push(u + ' is no longer in SAMPLE_FILES');
    console.error('public/sound-data.js is out of date (' + (why.join('; ') || 'only the header or layout differs') + ') — run: node tools/embed-sounds.js');
    process.exit(1);
  }
  console.log('sound-data.js is current: ' + urls.length + ' recordings, ' + Math.round(text.length / 1024) + ' KB');
} else {
  fs.writeFileSync(out, text);
  console.log('wrote public/sound-data.js: ' + urls.length + ' recordings, ' + Math.round(text.length / 1024) + ' KB');
}
